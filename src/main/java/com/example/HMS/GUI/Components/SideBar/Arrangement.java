package com.example.HMS.GUI.Components.SideBar;

/**
 * How items are laid out inside the sidebar.
 */
public enum Arrangement {
    /** Single column, items stretch to the sidebar width. */
    GRID,
    /** Vertical box layout. */
    BOX_Y,
    /** Horizontal box layout. */
    BOX_X,
    /** Wrapping flow layout. */
    FLOW
}
